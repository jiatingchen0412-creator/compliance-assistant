@lru_cache(maxsize=4096)
def tokenize(text: str) -> str:
    """jieba 分词 -> 空格分隔 token 串。结果缓存，重复查询更快。"""
    if not text:
        return ""
    cleaned = re.sub(r"\s+", " ", str(text))

    # 保护条款编号这类带点号的数字：jieba 会把 "8.1.4.1" 切成 "8.1" + "4.1"，
    # 导致按编号精确检索时匹配不上。这里先把完整编号单独抽出来作为 token。
    protected = re.findall(r"\d+(?:\.\d+)+", cleaned)

    tokens = [t.strip() for t in jieba.lcut(cleaned) if t.strip()]
    # 过滤纯标点
    tokens = [t for t in tokens if re.search(r"[\w\u4e00-\u9fff]", t)]

    # 把被切碎的编号残片（"8.1"、"4.1"）丢掉——它们既是噪音，
    # 又可能误匹配到别的条款编号（比如 "4.1" 撞上别的标准里的条款号）。
    # 完整编号本身在下一步会被补回来，所以丢掉残片不影响按编号检索。
    protected_set = set(protected)
    if protected_set:
        tokens = [
            t for t in tokens
            if t in protected_set
            or not any(t != pid and t in pid for pid in protected_set)
        ]

    tokens.extend(protected)
    # 去重但保持顺序
    seen: set[str] = set()
    ordered: list[str] = []
    for t in tokens:
        if t not in seen:
            seen.add(t)
            ordered.append(t)
    return " ".join(ordered)


@lru_cache(maxsize=2048)
def expand_query(text: str) -> list[str]:
    """把用户口语扩展成检索用的关键词列表。

    结果去重但保持顺序。去重是必要的：一句话里往往同时命中多个口语词，
    而它们指向同一个术语（"共用一个管理员账号"会同时命中"共用"和
    "管理员账号"，都映射到"访问控制"），不去重就会让同一个词被重复计入。
    """
    if not text:
        return []
    lowered = text.lower()
    extra: list[str] = []
    seen: set[str] = set()
    for spoken, terms in COLLOQUIAL_MAP.items():
        if spoken in lowered:
            for term in terms:
                if term not in seen:
                    seen.add(term)
                    extra.append(term)
    return extra


def build_search_text(*parts: str | None) -> str:
    """把多个字段拼成用于建索引的文本。"""
    return tokenize(" ".join(p for p in parts if p))
