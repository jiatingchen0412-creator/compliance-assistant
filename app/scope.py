def clarify_notice() -> str:
    """问题太笼统时，拼在回答最前面的提示。

    为什么非要单独拼一段：模型漏问的时候，它给的那段结论读起来是
    "已经看过你的情况了"的口吻（"您的系统可能存在……"）。用户是不懂技术的，
    很容易把那当成针对自己的判断。所以要让用户第一眼就看到"我还没法判断"，
    而不是把希望寄托在模型自觉上。
    """
    return (
        "⚠️ 您说的情况还比较笼统，我先没法给出针对性的结论——"
        "同一个说法在不同系统上对应的条款可能完全不同。\n"
        "下面只是相关知识库条款的大致说明，具体怎么落到您这边，"
        "需要您先补充下面几个情况。\n"
    )


def out_of_kb_notice(
    names: list[str], *, from_answer: bool = False, removed: int = 0
) -> str:
    """点名了知识库外的法规时，拼在回答最前面的说明。

    这段话由服务端生成、强制拼接，模型删不掉。
    措辞要点：**先说不能做什么**（不转述该法规条文），
    再说还能做什么（给出库里真实收录的相关条款），最后给行动建议。

    from_answer=True 表示这条法规不是用户问的，而是**模型自己在回答里写了**
    （H-2）。这时不能再说"您提到的"，也不能假装回答里还有相关内容——
    得如实告诉用户：这些内容已被服务端删掉。
    """
    if not names:
        return ""
    listed = "、".join(names)
    covered = "、".join(COVERED_STANDARDS)
    if from_answer:
        head = (
            f"⚠️ 补充说明：本次回答提到了 {listed}，但该法规不在本工具的知识库范围内（未收录）。\n\n"
            f"本工具目前只收录了三套标准：{covered}。\n"
        )
        if removed:
            head += (
                f"回答里涉及该法规的 {removed} 处转述已由服务端删除——"
                "这类内容我不能凭记忆转述，转了也无法保证准确，那正是最容易误导您的地方。\n"
            )
        else:
            head += (
                "本回答不把该法规的条文当作知识库依据；"
                "若正文里仍出现相关字句，那是未经核实的转述，请以官方发布文本为准。\n"
            )
        head += "如果需要该法规的准确条文，请查阅官方发布文本，或咨询专业安全顾问。\n\n"
        return head
    return (
        f"⚠️ 先说明一点：您提到的 {listed} 不在本工具的知识库范围内。\n\n"
        f"本工具目前只收录了三套标准：{covered}。\n"
        f"所以下面的回答**不以 {listed} 的条文为依据**——"
        f"这类内容我不能凭记忆转述，转了也无法保证准确，那正是最容易误导您的地方。\n"
        f"若正文里仍出现该法规的字句，那是未经核实的转述，请以官方发布文本为准。\n"
        f"如果需要该法规的准确条文，请查阅官方发布文本，或咨询专业安全顾问。\n\n"
        f"下面是知识库里确实收录的、与您问题主题相关的条款，供您对照参考。\n"
    )


def needs_context_answer(reason: str, clauses: list[dict]) -> str:
    """不可判定问题的回答：由服务端直接产出，不走大模型。

    这类问题的正确答案本身就是"无法判定 + 说明为什么 + 给出路"，
    让模型去编一份条款清单只会害人。所以这里**刻意不调模型**。
    """
    lines = [
        "这个问题我无法给您一个可靠的结论——不是检索失败，"
        "而是它没法在不了解您系统具体情况的前提下判断。",
        "",
        f"判定依据：{reason}。",
        "像「这套系统算几级」「要不要做等保」「哪些条款适用于我们」这类问题，"
        "都属于适用性判定，要结合系统的定级结果、业务范围、部署模式和数据类型"
        "逐条比对才能回答。",
        "本工具只能帮您把标准条款检索出来，不能替您下结论——"
        "硬给一个判断或一份清单，反而是最容易把您带偏的做法。",
        "",
        "要拿到可用的结论，建议：",
        "1. 先确认您的系统定级是二级还是三级（这直接决定适用哪一档要求）。",
        "2. 做一次正式的适用性分析或差距分析。这属于等保测评的工作范围，"
        "建议委托有资质的测评机构或专业安全顾问来做。",
        "",
        "下面是知识库中与您问题相关的条款，可以先作为自查参考：",
        "",
    ]
    for i, c in enumerate(clauses[:5], 1):
        risks = c.get("risk_tags") or []
        mark = "⚠️ " if any(
            r in {"encryption", "access_control", "personal_info"} for r in risks
        ) else ""
        lines.append(f"{i}. {mark}【{c.get('standard_name')}】{c.get('clause_id')} {c.get('title')}")
        body = (c.get("summary") or c.get("text") or "")[:100]
        if body:
            lines.append(f"   {body}")
        lines.append("")
    lines.append("本回答仅用于辅助自查，不构成正式测评结论。")
    return "\n".join(lines)


def needs_context_reply(
    reason: str, clauses: list[dict], names: list[str] | None = None
) -> str:
    """不可判定分支的完整回答：用户点名了库外法规时，先把「未收录」声明拼在最前面。

    H-6：原来这个分支只把 `out_of_kb` 放进结果字段、却不拼声明，
    用户看到的是一份等保条款清单 + "无法判定"，压根不知道
    自己问的那部法规根本没被收录。声明必须由服务端强制拼接。
    """
    body = needs_context_answer(reason, clauses)
    notice = out_of_kb_notice(names or [])
    return (notice + "\n" + body) if notice else body


def merge_out_of_kb(*groups: list[dict] | None) -> list[dict]:
    """合并多来源的库外法规识别结果（问题 / 回答 / 会话上下文），按名字去重保序。"""
    merged: list[dict] = []
    seen: set[str] = set()
    for group in groups:
        for item in group or []:
            if not isinstance(item, dict):
                continue
            name = str(item.get("name") or "")
            if not name or name in seen:
                continue
            seen.add(name)
            merged.append(item)
    return merged


# 追问上一轮提到的法规时，问题里往往只剩「第十三条」「那条怎么规定的」这类指代。
_FOLLOWUP_HINT = re.compile(
    r"第\s*[\d一二三四五六七八九十百]+\s*[条章节款项]"
    r"|条款\s*[\d一二三四五六七八九十]+"
    r"|(它|该法|这部法|这条|那条|上面|刚才)[^。？！?；;]{0,12}"
    r"(规定|要求|内容|怎么写|说什么|怎么写的)"
)
# 出现这些词说明用户已经换到别的话题了，不能再把上一轮的法规带进来。
_TOPIC_RESET = ("等保", "等级保护", "NIST", "OWASP", "8.1.", "PR.AA", "A01:", "A03:")


def followup_out_of_kb(question: str, history_text: str) -> list[dict]:
    """多轮绕过兜底：本轮没点名法规、但看起来在追问上一轮提到的条文时，
    把上一轮识别到的库外法规带回本轮判定。

    为什么需要：第一轮问「《个人信息保护法》第13条」会被拦下并被告知未收录，
    第二轮只问「第十三条具体怎么规定的」，问题里就没有法规名了——
    原来的实现会直接交给模型，模型照样凭记忆把条文吐出来。
    只读问题不看会话，等于第一轮的拦截白做了。

    判据刻意窄（宁可漏判也不误判成"还在聊那部法规"）：
      ① 问题里必须有条号或指代词；
      ② 没有出现等保 / NIST / OWASP / 具体条款编号这类"已经换话题"的信号。
    只在调用方已判定「本轮问题本身没命中库外法规」时才调用。
    """
    text = (question or "").strip()
    if not text or not history_text:
        return []
    probe = normalize_for_match(text)
    if any(k in probe for k in _TOPIC_RESET):
        return []
    if not _FOLLOWUP_HINT.search(probe):
        return []
    return detect_out_of_kb(history_text)


