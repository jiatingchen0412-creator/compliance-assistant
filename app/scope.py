def _compile_alias(alias: str) -> re.Pattern:
    """把别名编译成"每个字之间都允许有空白"的正则。

    为什么要放开空白：用户可能写 "ISO27001"、也可能写 "ISO 27001"，
    可能写 "个人信息保护法"、也可能手滑写成 "个人信息 保护法"。
    这些写法指的是同一部法规，应该都认出来。

    为什么只放开空白：法规名差一个字就是另一部法规。
    "《个人信息保护条例》"和"《个人信息保护法》"是两份不同效力的文件，
    所以绝不能做模糊匹配或去掉字词，宁可漏判也不能误判。
    """
    parts = [re.escape(ch) for ch in str(alias) if not ch.isspace()]
    if not parts:
        return re.compile(r"(?!)")  # 空别名永不匹配
    return re.compile(r"\s*".join(parts), re.I)


_ALIAS_PATTERNS: list[tuple[str, str, str, re.Pattern]] = [
    (name, alias, why, _compile_alias(alias))
    for name, aliases, why in OUT_OF_KB_REGULATIONS
    for alias in aliases
]

# 法规显示名 -> 全部写法。detect_out_of_kb 会把它带出去，
# 供 guard.strip_out_of_kb_claims 清理模型输出时使用。
_ALL_ALIASES: dict[str, list[str]] = {
    name: list(aliases) for name, aliases, _ in OUT_OF_KB_REGULATIONS
}


def detect_out_of_kb(question: str) -> list[dict]:
    """找出问题里点名了、但知识库没收录的法规。

    返回 `[{name, aliases, all_aliases, why}]`，按在问题中出现的先后去重排序。
    其中 `aliases` 只包含**这次问题里真的用到**的写法，`all_aliases` 是这部
    法规的全部写法——下游清理模型输出时两种都需要：
    用户问的是"《个人信息保护法》"，模型却可能在回答里写"PIPL"，
    只拿 aliases 去匹配就会漏掉，让编造的内容留在正文里。
    """
    text = question or ""
    hits: dict[str, dict] = {}
    positions: dict[str, int] = {}

    for name, alias, why, pattern in _ALIAS_PATTERNS:
        m = pattern.search(text)
        if not m:
            continue
        entry = hits.setdefault(name, {
            "name": name,
            "aliases": [],
            "all_aliases": _ALL_ALIASES.get(name, []),
            "why": why,
        })
        if alias not in entry["aliases"]:
            entry["aliases"].append(alias)
        # 记最早的命中位置，保证输出顺序和用户在问题里的提问顺序一致
        positions[name] = min(positions.get(name, m.start()), m.start())

    return [hits[n] for n in sorted(hits, key=lambda k: positions[k])]


def out_of_kb_names(question: str) -> list[str]:
    return [h["name"] for h in detect_out_of_kb(question)]


# --------------------------------------------------------------------------
# 不可判定问题
# --------------------------------------------------------------------------
# 只拦截一类：要求**枚举"哪些条款不适用/没覆盖"**的提问。
# 这类问题的答案是"要结合你的系统才能判定"，任何条款清单式回答都是错的。
#
# 刻意写得窄：只有同时出现"枚举动作"和"否定性适用词"才算。
# 例如"我们用了 HTTPS 还要做什么"不会命中（没有枚举动作），
# "等保三级有哪些要求"也不会命中（没有否定词）。
_UNDETERMINABLE_PATTERNS: list[re.Pattern] = [
    # 列出 / 哪些 … 不适用 / 用不上 / 未覆盖
    re.compile(
        r"(列出|列举|哪些|哪几|找出|整理|汇总|统计|给我)[^。？！?；;]{0,14}"
        r"(不适用|用不上|用不着|不涉及|不需要|未覆盖|没有覆盖|没覆盖)"
    ),
    # 不适用 / 未覆盖 … 的条款（条目 / 项 / 要求 / 控制项）
    re.compile(
        r"(不适用|用不上|用不着|不涉及|不需要|未覆盖|没有覆盖)[^。？！?；;]{0,10}"
        r"(的)?(条款|条目|控制项|要求|项)"
    ),
    # 适用性判定 / 适用性分析
    re.compile(r"适用性[^。？！?；;]{0,6}(判定|判断|分析|结论)"),
    # "这条对我们适用吗"式的单条判定——同样需要系统上下文。
    # 中间那段要留够宽度：实测「这条 8.1.4.1 对我们适用吗？」在"这条"和
    # "适用"之间夹了 12 个字符（条款编号 + "对我们"），窄了就会漏判，
    # 而这类问题检索分数往往很高（0.966），阈值闸门拦不住它。
    re.compile(r"(这条|该条|这一条)[^。？！?；;]{0,14}(适用|适用于我们|用得上吗|用得上)"),
]

# 命中时给用户的解释里，用来指认"到底是哪种问法"
_UNDETERMINABLE_LABEL = "要求判断条款适用性"


def needs_system_context(question: str) -> tuple[bool, str]:
    """判断问题是否属于"无法在不了解具体系统的前提下回答"。

    返回 (是否不可判定, 命中的原因说明)。
    """
    text = question or ""
    for pattern in _UNDETERMINABLE_PATTERNS:
        m = pattern.search(text)
        if m:
            return True, f"{_UNDETERMINABLE_LABEL}（命中「{m.group(0).strip()}」）"
    return False, ""


# --------------------------------------------------------------------------
# 信息不足、应该先追问
# --------------------------------------------------------------------------
# 为什么这件事也要服务端兜底：
# 提示词里写了"情况B：用户只说了很笼统的话就追问"，但 7B 模型经常漏做——
# 实测问"我们公司到底需不需要做等保？""我们的数据安全吗？"时，
# 模型直接给了一段泛泛而谈的结论，一个反问都没有。而这段泛泛的结论
# 反而比不答更危险：用户会以为系统看过他的情况了。
#
# 判定必须**又准又窄**，因为误判的代价是"用户问了具体问题却被反问"，
# 比漏判还烦人。所以要求同时满足三个条件：
#   ① 问题很短（长问题通常自带上下文）
#   ② 命中了"要结论/要估价"这种笼统问法
#   ③ **完全没有**任何具体问题的线索（人物、资产、动作、数字）
# 任何一条不满足就不追问。
_VAGUE_QUESTION_PATTERNS: list[re.Pattern] = [
    # "安全吗 / 合规吗 / 合理吗 / 有没有问题" —— 要一个整体性结论
    re.compile(r"(安全吗|安全么|合规吗|合规么|有问题吗|有没有问题|合理吗|靠谱吗|行不行)"),
    # "要不要 / 需不需要" + 一件合规大事
    re.compile(r"(要不要|需不需要|需要吗|用不用)[^。？！?；;]{0,8}(等保|合规|备案|测评|认证|做)"),
    # "要花多少钱 / 贵不贵 / 难不难" —— 要一个估价或难度
    re.compile(r"(多少钱|花很多钱|贵不贵|贵吗|难不难|简单吗|要多久|多长时间)"),
]

# 出现任何一个，就说明用户其实讲了具体的情形，不该追问。
# 这些词挑的都是"具体问题才有"的名词，不是泛泛的领域词。
_CONTEXT_NOUNS = (
    # 资产与对象
    "账号", "账户", "权限", "口令", "密码", "密钥", "证书",
    "日志", "审计", "备份", "补丁", "漏洞", "注入", "病毒", "勒索", "泄露",
    "身份证", "手机号", "人脸", "指纹", "隐私", "个人信息", "客户信息",
    # 部署与形态
    "部署", "自建", "托管", "云上", "阿里云", "腾讯云", "华为云",
    "小程序", "网站", "接口", "后台", "机房", "内网", "外网", "数据库", "服务器",
    # 人与流程
    "离职", "回收", "培训", "外包", "供应商", "第三方", "制度", "责任人", "专员",
    # 定级与范围（这些一提就说明用户知道自己在问哪一档）
    "三级", "二级", "四级", "扩展要求", "定级",
)

# 长过这个字数就认为用户已经交代了足够的情形。
_MAX_VAGUE_CHARS = 24

# 服务端兜底的追问。刻意问成"选择题"而不是"填空题"——
# 用户是不懂技术的，让他打一大段字描述系统很难，勾选项容易得多。
CLARIFY_FOLLOWUPS: list[str] = [
    "您的系统是自建的、买的云服务，还是外包做的？",
    "系统里存了哪些数据？有没有客户的手机号、身份证这类个人信息？",
    "系统大概多少人用？有没有连互联网、有没有专职的信息安全人员？",
]


def needs_clarification(question: str) -> bool:
    """问题是否笼统到"先给出针对性建议"的程度，应该先追问。

    只在本模块的规则**有把握**时才返回 True——宁可漏判（交给模型自己判断），
    也不要误判（用户问了具体问题却被反问一圈）。
    """
    text = (question or "").strip()
    if not text or len(text) > _MAX_VAGUE_CHARS:
        return False
    # 数字（人数、条款号、时间）本身就是上下文
    if re.search(r"\d", text):
        return False
    if any(noun in text for noun in _CONTEXT_NOUNS):
        return False
    return any(p.search(text) for p in _VAGUE_QUESTION_PATTERNS)


