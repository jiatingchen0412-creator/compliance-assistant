_TRAD_TABLE = str.maketrans(_TRAD2SIMP)


# 零宽字符：NFKC **不会**去掉它们，但粘贴来的文本里经常夹着
# （"个人信\u200b息保护法"）。不先剥离，任何按字面匹配的防线都会被一个
# 不可见字符整体绕过。
# U+3164（HANGUL FILLER）与 U+115F/U+1160 属于"看起来是空白、实际是字母"的
# 填充符，Unicode 类别是 Lo 而不是 Cf，_strip_invisible 的 Cf 过滤抓不到，
# 所以单独列出来。
_ZERO_WIDTH = re.compile(r"[\u200b-\u200f\u2060\ufeff\u00ad\u115f\u1160\u3164\uffa0]")


def _strip_invisible(text: str) -> str:
    """剥掉所有 Unicode Cf（格式/不可见）字符。

    NFKC **不会**去掉 U+200B / U+2063 / U+FEFF 这类字符，而它们夹在法规名
    中间时，任何按字面匹配的防线都会被整体绕过（第三轮红队用 U+2063 复现过）。
    这里按 Unicode 类别整体剥离，而不是维护一个越补越长的码位黑名单——
    黑名单只能堵住见过的那几个，类别能挡住还没见过的。
    """
    return "".join(ch for ch in str(text) if unicodedata.category(ch) != "Cf")


def normalize_for_match(text: str) -> str:
    """把零宽字符、繁体、全角写法收敛成别名表里的写法。

    顺序要紧：先剥不可见字符（NFKC 管不着），再 NFKC（ＧＤＰＲ→GDPR、１７→17），
    最后繁→简。三者都不改变语义，调用方可以放心只在匹配时用。
    """
    stripped = _strip_invisible(text or "")
    stripped = _ZERO_WIDTH.sub("", stripped)
    normalized = unicodedata.normalize("NFKC", stripped)
    normalized = normalized.translate(_TRAD_TABLE)
    # 等级写法归一：第四轮红队用「第三等级 / 等级3」绕开了以「级」为锚点的判定。
    # 这不是枚举问法，而是把同义的等级写法收敛成「N级」——收敛之后锚点仍然只有
    # 一个（级），不必为每种写法再加一条正则。
    normalized = re.sub(r"第\s*([一二三四五1-5])\s*等级", r"第\1级", normalized)
    normalized = re.sub(r"等级\s*([1-5])", r"\1级", normalized)
    return normalized


# 法规名匹配专用噪声：点号、空格、括号会把法规名拆开
# （"《个人信息·保护法》"、"个人 信息 保护法"、"「个人信息保护法」"）。
# 别名表本身不含标点，所以把待匹配文本的标点与空白整体去掉再做一次匹配，
# 就能一次覆盖"中间加点/加空格/加括号"的各种插法。
_MATCH_NOISE = re.compile(
    r"[\s·•・∙⋅‧\-—_/\\|,，.。、;：:！!?？\"'“”‘’()（）\[\]【】《》<>〈〉「」『』]"
)


def law_match_text(text: str) -> str:
    """法规名匹配专用文本：归一化 + 去掉标点与空白。"""
    return _MATCH_NOISE.sub("", normalize_for_match(text or ""))


_ALIAS_PATTERNS: list[tuple[str, str, str, re.Pattern]] = [
    (name, alias, why, _compile_alias(alias))
    for name, aliases, why in OUT_OF_KB_REGULATIONS
    for alias in aliases
]

# 法规显示名 -> 全部写法。detect_out_of_kb 会把它带出去，
# 供 guard.strip_out_of_kb_claims 清理模型输出时使用。
_ALL_ALIASES: dict[str, list[str]] = {
    name: list(aliases) for name, aliases, _ in OUT_OF_KB_REGULATIONS
}


def detect_out_of_kb(question: str) -> list[dict]:
    """找出问题里点名了、但知识库没收录的法规。

    返回 `[{name, aliases, all_aliases, why}]`，按在问题中出现的先后去重排序。
    其中 `aliases` 只包含**这次问题里真的用到**的写法，`all_aliases` 是这部
    法规的全部写法——下游清理模型输出时两种都需要：
    用户问的是"《个人信息保护法》"，模型却可能在回答里写"PIPL"，
    只拿 aliases 去匹配就会漏掉，让编造的内容留在正文里。
    """
    # 归一化后再匹配：繁体「個人信息保護法」、全角「ＧＤＰＲ」都要能认出来；
    # loose 版再把标点与空白去掉，挡住「个人信息·保护法」「个人 信息 保护法」。
    text = normalize_for_match(question or "")
    loose = _MATCH_NOISE.sub("", text)
    hits: dict[str, dict] = {}
    positions: dict[str, int] = {}

    for name, alias, why, pattern in _ALIAS_PATTERNS:
        m = pattern.search(text) or pattern.search(loose)
        if not m:
            continue
        entry = hits.setdefault(name, {
            "name": name,
            "aliases": [],
            "all_aliases": _ALL_ALIASES.get(name, []),
            "why": why,
        })
        if alias not in entry["aliases"]:
            entry["aliases"].append(alias)
        # 记最早的命中位置，保证输出顺序和用户在问题里的提问顺序一致
        positions[name] = min(positions.get(name, m.start()), m.start())

    return [hits[n] for n in sorted(hits, key=lambda k: positions[k])]


def out_of_kb_names(question: str) -> list[str]:
    return [h["name"] for h in detect_out_of_kb(question)]


# --------------------------------------------------------------------------
# 不可判定问题
# --------------------------------------------------------------------------
# 拦截"要结合你的系统才能判定"的提问：适用性判定、定级、关基认定。
# 这类问题的正确答案都是"无法在不了解系统的情况下判断"，
# 任何直接给的结论（尤其是条款清单）都是错的。
#
# 写法刻意窄：宁可漏判（交给模型自己判断），也不能把真问题拦下来。
# 例如"等保三级有哪些要求"不会命中（没有判定动作），
# "我们的系统要做等保三级，需要满足哪些技术要求"也不会命中（那是问要求，不是问定级）。
_UNDETERMINABLE_PATTERNS: list[re.Pattern] = [
    # 列出 / 哪些 … 不适用 / 用不上 / 未覆盖
    re.compile(
        r"(列出|列举|哪些|哪几|找出|整理|汇总|统计|给我)[^。？！?；;]{0,14}"
        r"(不适用|用不上|用不着|不涉及|不需要|未覆盖|没有覆盖|没覆盖)"
    ),
    # 不适用 / 未覆盖 … 的条款（条目 / 项 / 要求 / 控制项）
    re.compile(
        r"(不适用|用不上|用不着|不涉及|不需要|未覆盖|没有覆盖)[^。？！?；;]{0,10}"
        r"(的)?(条款|条目|控制项|要求|项)"
    ),
    # 适用性判定 / 适用性分析
    re.compile(r"适用性[^。？！?；;]{0,6}(判定|判断|分析|结论)"),
    # "这条对我们适用吗"式的单条判定——同样需要系统上下文。
    # 中间那段要留够宽度：实测「这条 8.1.4.1 对我们适用吗？」在"这条"和
    # "适用"之间夹了 12 个字符（条款编号 + "对我们"），窄了就会漏判，
    # 而这类问题检索分数往往很高（0.966），阈值闸门拦不住它。
    re.compile(r"(这条|该条|这一条)[^。？！?；;]{0,14}(适用|适用于我们|用得上吗|用得上)"),
    # 定级类：「我们这套系统算不算三级」「属于几级」「该定几级」。
    # 定级要结合业务受到破坏后的危害程度，模型不可能知道，只能编一个数字。
    # 只认"判定动作"（算/属于/该定/应该定），不认"我们公司是三级系统"这种陈述句。
    re.compile(
        r"(算不算|算|属于|是不是|该定|应该定|需要定|定为|定级为)"
        r"[^。？！?；;]{0,8}(几级|哪一级|第几级|三级|二级|四级)"
    ),
    # 「是三级吗」「属于二级系统吗」——带明确问号才算，陈述句不算
    re.compile(r"(是|属于)[^。？！?；;]{0,4}(三级|二级|四级|几级)[^。？！?；;]{0,2}(吗|么|？|\?)"),
    # 要不要 / 需不需要 做等保、定级、测评、认证
    re.compile(
        r"(要不要|需不需要|是否需要|需要|必须|用不用)"
        r"[^。？！?；;]{0,8}(做|过|搞|申请|参加)?[^。？！?；;]{0,4}"
        r"(等保|等级保护|定级|测评|认证)"
    ),
    # 关基 / 关键信息基础设施运营者认定
    re.compile(
        r"(算不算|是不是|属于|是否属于|用不用|要不要)[^。？！?；;]{0,10}"
        r"(关基|关键信息基础设施)"
    ),
    # 泛化的适用性问法：「这个要求对我们适用吗」「哪些要求适用于我们」
    re.compile(r"(适用|适用于)(我们|咱们|我公司|我们公司)"),
    re.compile(r"(对我们|对咱们|对我公司|对我们公司)[^。？！?；;]{0,8}(适用|管用|用得上)"),
    re.compile(r"(哪些|哪几条|哪几条要求|哪几项)[^。？！?；;]{0,12}(适用于|适用)"),
    # 「我们不做等保行不行」——问的是"我们到底要不要做"，答案取决于系统定级，
    # 没有等级锚点也要拦。判据是「否决/免除 + 等保/测评 + 求许可尾巴」。
    re.compile(
        r"(不|别|免|不用)(做|过|搞|上|参加)?[^。？！?；;]{0,6}(等保|等级保护|测评|定级)"
        r"[^。？！?；;]{0,8}(行不行|行吗|可以吗|成不成|要紧吗|有事吗|会怎样|有没有问题|可以么)"
    ),
    # 「能不能免于等保」「跳过测评行不行」「不备案可以吗」——问的是
    # "这件义务我们到底要不要履行"，答案同样取决于系统定级，没有等级词也要拦。
    re.compile(
        r"(不做|别做|免于|免除|豁免|跳过|不测评|不备案|不整改|不建设|"
        r"不用做|不需要做|可以不做|能不能不做)"
        r"[^。？！?；;]{0,10}(等保|等级保护|测评|定级|备案|整改|建设)"
        r"[^。？！?；;]{0,10}(行不行|行吗|可以吗|成不成|能不能|要紧吗|吗|么|？|\?)"
    ),
]

# --- 结构化特征：不再枚举问法 --------------------------------------------
# 教训：t11 独立复验只换了三句话——「等保要定到哪一级」「帮我们判断一下适用性」
# 「要按几级来建设」——就绕过了上面所有枚举式正则，模型照样输出"你们应当按三级建设"。
# 枚举问法永远慢一步，所以这里改成判**特征组合**：
#   分级词（在问"几级 / 定级 / 定到哪级 / 按几级"）
#   × 判定动作（要结论、要做法、要判断）
# 两者同时出现就拦，允许任意顺序、允许中间夹字。宁可多拦一句（追问一句不伤人），
# 不可漏判——漏判是直接替用户下结论，比多问一句危险得多。
_LEVEL_FEATURE = re.compile(
    r"(几级|哪级|哪一级|第几级|什么级别|哪个级别|定级|分级|定个?级(别)?|"
    r"第?\s*[一二三四五1-5]\s*级|Level\s*[1-5]|"
    r"(?:做到|评到|建设到|达到|整改到)\s*(?:第\s*)?[一二三四五1-5]\s*级|"
    r"定到|定为|定成|按\s*[一二三四五\d]+\s*级|"
    r"(?:只|就|先|直接)?做\s*[一二三四五\d]\s*级|"
    r"等级\s*(?:是\s*多少|是多少|多少|是什么|是啥|怎么定|如何定)|"
    r"什么等级|哪个等级|"
    r"级别\s*(怎么|如何|该|应|是几|多高|定))",
    re.I,
)
# 判定动作只收「在要结论」的写法。刻意**不收**「需要 / 必须 / 怎么 / 如何」：
# 它们是纯知识题的常见词（「等保三级需要做哪些技术措施」），收进来会把
# 该照常回答的问题拦成追问。要结论的问法一定有下面这些尾巴之一。
_JUDGE_FEATURE = re.compile(
    r"(适用|判断|确定|分析|结论|要不要|需不需要|是否需要|该不该|能不能|可不可以|"
    r"行不行|行吗|可以吗|可以了吗|够不够|够吗|够了吧|合适|对不对|好吗|"
    r"对吧|是吧|行了吧|没问题吧|没问题吗|能过|过关|过得去|"
    r"按.{0,10}(建|建设|做|整改|定)|"
    r"定到|定为|定成|建设|整改|评(为|定))"
)
# 「等保 / 等级保护」主题下出现建设、测评、整改、定级这类词，问的往往就是
# "我们该做到哪一级"。它未必带「几级」，所以单独作为一条意图特征。
_ES_LEVEL_INTENT = re.compile(
    r"((?:等保|等级保护).{0,12}(?:建设|测评|整改|定级|备案)|"
    r"(?:建设|测评|整改|定级|备案).{0,12}(?:等保|等级保护))"
)
# 「适用性」词根本身就足够——不必再要求后面跟"判定/分析"
_APPLICABILITY_ROOT = re.compile(r"(适用性|适不适用|适不适合|是否适用|对我们适用)")

# 只出现分级词、没有出现动作词的问法：『我们这套系统该评到第几级比较合适？』
# 『按等保要评个什么级别？』——「该」「评到」「比较合适」都不在动作词里，但
# 定级这件事本身就要求先知道系统边界与业务重要性，只要问的是"我们自己的系统"，
# 一个分级词就足够拦。反过来，『等保三级和二级有什么区别』这种纯知识题没有
# 分级词（"三级"不在词表里），不会被误伤。
_OWN_SYSTEM = re.compile(
    r"(我们|咱们|我公司|本公司|公司|系统|平台|业务|这套|上线|服务器|规模|左右|大概|多少人)"
)
# 已经定过级、在问后续流程的（『定级之后要做测评吗』），不算替用户下结论
_ALREADY_LEVELED = re.compile(r"(之后|以后|完后|过了|已过|已经过|定完|评完)")
# 等级被当成**属性**用而不是当结论下：「三级系统」「做等保三级」「三级的要求」。
# 这类是知识题（"我们公司是三级系统，现在缺哪些日志"），不能拦成追问。
# 反过来「按三级建设」「定到三级」「算不算三级」是在要结论，仍然要拦。
_LEVEL_AS_ATTRIBUTE = re.compile(
    r"(第?\s*[一二三四五1-5]\s*级\s*(系统|平台|要求|标准|条款|日志|措施|规范|基线|配置|指标|保护|安全|测评)|"
    r"(?:做|过|上了)\s*(?:等保|等级保护)?\s*[一二三四五1-5]\s*级)"
)

# 命中时给用户的解释里，用来指认"到底是哪种问法"
_UNDETERMINABLE_LABEL = "要求判断条款适用性"

# --- 闭集锚点（第四轮）：不再枚举「三级 / 第3级 / Level 3 / L3 / T3」 ----------
# 前三轮反复失败的原因是同一个：把"等级的所有写法"当成有限集合去枚举，
# 红队每次换一种写法（L3、T3、第三等级、叁级、等级3、日文）就绕过去了。
# 但中文里任何等级表达都绕不开「级 / 級」这个字，英文变体一定带
# L / Level / T + 数字——所以锚点只认这个**闭集**，不认"怎么说三级"。
_LEVEL_ANCHOR_SRC = (
    r"(级|級|[Ll]v?\s*-?\s*\d|Level\s*-?\s*\d|(?<![A-Za-z0-9])[Tt]\s*-?\s*\d)"
)
_LEVEL_ANCHOR = re.compile(_LEVEL_ANCHOR_SRC, re.I)
# 档位表达（第五轮）：红队把「三级」换成「第三档 / 第2层 / 梯队 / tier」后，
# 只认「级」的锚点就漏了。档/阶/层这类词单独出现太容易误伤（"三层架构"），
# 所以只认**带序数或档位后缀**的形式，并与"自有系统主语 × 判定动作"组合判定。
_TIER_WORD = re.compile(
    r"(第\s*[一二三四五1-5一二三四五六七八九十]+\s*(?:档|阶|层|类|等)|"
    r"[一二三四五1-5]\s*(?:星|等|类)(?:标准|要求|级)?|"
    r"档位|梯队|规格|tier\s*-?\s*\d?|level\s*-?\s*\d|等第|档|阶|层)",
    re.I,
)
# 等级锚点 + 这些动作即拦，不再要求问题里出现「等保/等级保护」。
_LEVEL_ACTION = re.compile(
    r"(定级|分级|建设|整改|测评|备案|定到|建到|做到|评到|达到|算|属于|定|拟)"
)
# 第二人称：判断"要不要替用户下结论"时的信号之一
_SECOND_PERSON = re.compile(r"(您|你|你们|贵司|贵公司|贵单位|咱们|咱公司)")
# 跨轮指代：本轮没提等级，但上一轮提过，用户说"按这个/照上面"
_REFERRAL = re.compile(
    r"(按这个|照这个|按上面|照上面|按刚才|照刚才|就按这个|按那个|上面说的|刚才说的|"
    r"这个方案|那个方案|按你说的|照你说的)"
)
# 锚点只有落在"等保 / 定级 / 测评"语境里才是在问等级判定；
# 「A 级机房」「三级菜单」这类无关用法不能被拦。
_LEVEL_CONTEXT = re.compile(r"(等保|等级保护|定级|分级|测评|备案|保护等级|安全等级)")
# 「按 L3 建设行不行」这类没提"等保"的句子，锚点 + 决定动作本身就在要结论。
# 判据只认"按/做到/建到…+ 等级"，不认裸的等级词，避免把知识题一起拦掉。
_LEVEL_DIRECTIVE = re.compile(
    r"(按|按照|做到|建到|建设到|整改到|达到|评到|定到|定|做)\s*(?:第\s*)?"
    r"(?:[^。？！?；;]{0,6}?)(级|級|[Ll]v?\s*-?\s*\d|Level\s*-?\s*\d|(?<![A-Za-z0-9])[Tt]\s*-?\s*\d)",
    re.I,
)
# 知识型问法白名单：问的是标准里写了什么，不是要我们替用户判定。
_LEVEL_KNOWLEDGE = re.compile(
    r"(有哪些|哪几条|哪几项|哪几类|缺哪些|缺什么|要补哪些|有什么|怎么规定|如何规定|规定了什么|"
    r"包括什么|内容是什么|是什么|讲什么|要求是什么|有什么区别|区别|有什么不同|"
    r"对比|含义|定义|要做什么|怎么做|如何做|需要做什么|需要满足|要满足|"
    r"分几级|分几个级别|怎么划分|如何划分|怎么分|划分|"
    r"保存多久|留存多久|保存期限|留存期限|多长时间|多久|"
    r"哪些测评|测评项|需要做哪些|要做哪些|要求包括|要求是|包括哪些|包含哪些|"
    r"有哪些要求|有什么要求|"
    r"控制项|检查项|条款内容|标准原文|"
    r"流程|步骤|有哪些步骤|包括哪些步骤|需要哪些步骤)"
)
# 陈述式等级：用户自己给了等级、问的是后续流程
# （"我们系统已经定级为三级，还需要做等保测评吗？"）。这类不是求解，
# 整条拦成 needs_context 等于答非所问。
_LEVEL_STATEMENT = re.compile(
    r"(已经|已是|已定|已经定|定了|已评|评为|定为|已过|已经过|已经通过|通过了)"
    r"[^。？！?；;]{0,8}级"
)
# 但如果同一句里又在求解另一个等级（"已经定级为三级，还要按几级整改"），照拦。
_LEVEL_SOLVE = re.compile(
    r"(要定到|定到哪|该定|应该定|需要定|按几级|按\s*[一二三四五\d]\s*级|"
    r"属于几级|算几级|算不算|是不是|几级|哪一级|第几级|定个级(别)?|帮我定|"
    r"判断|确定|分析|评估)"
)

# --- 第六轮：改策略，不再枚举"等级怎么表达" --------------------------------
# 四轮失败的原因一模一样：把"三级的所有写法"当有限集合去枚举，而它是**开放集合**
# （三级 → 第3级 → L3 → T3 → 档 → 等 → 阶 → tier-3 → P3 → 3 星 → III … 枚举不完）。
# 这一轮反过来：不问"等级怎么写"，问"这句话是不是在向我们要一个关于自己系统的
# 合规判定"。判据是三个闭集同时成立：
#   ① 合规动作（等保/测评/定级/整改/建设/满足/符合/达到/够/备案/整改/达标）
#   ② 指向自己（我们/贵司/这套系统…）或明确在求结论（可以吗/够不够/吗…）
#   ③ 求结论的尾巴（吗/可以吗/够不够/多少/哪一…）
# 三者齐了就拦。知识型问法（"定级流程是什么""测评包括哪些步骤"）没有第③项，
# 照常放行——这就是它与"问我们要结论"的分界线。
_GRADE_ACTION = re.compile(
    r"(等保|等级保护|测评|定级|备案|整改|建设|达标|"
    r"满足|符合|达到|够)"
)
_DECISION_TAIL = re.compile(
    r"(吗|么|？|\?|可不可以|可以吗|可以|行不行|行吗|成不成|够不够|够吗|"
    r"符合|满足|达到|属于|算不算|要不要|需不需要|该不该|能不能|是不是|"
    r"对不对|合适|多少|几级|哪一级|第几级|什么级|什么档|什么等|"
    r"可以了吗|够了吧|行了吧|对吧|是吧|没问题吧|没问题吗)"
)



def _level_anchor_hit(text: str) -> str:
    """等级锚点命中片段（空串表示没有）。"""
    m = _LEVEL_ANCHOR.search(text)
    return m.group(0) if m else ""



def _grade_intent(question: str) -> tuple[bool, str]:
    """单轮判定：这句话是不是在要求"替用户判断等级/适用性"。

    返回 (是否不可判定, 命中的原因说明)。
    """
    # 同样先归一化：「第１７條对我們適用嗎」「个人信\u200b息保护法」都要能命中
    text = normalize_for_match(question or "")
    # 陈述式等级优先放行（RT18-03）：不先排除的话，下面的定级模式会把
    # 「我们系统已经定级为三级，还需要做等保测评吗？」误拦成"替用户下结论"。
    if _LEVEL_STATEMENT.search(text) and not _LEVEL_SOLVE.search(text):
        return False, ""
    # 知识型问法只豁免"要不要做等保/测评"那一条（问的是流程知识），
    # 其余枚举模式照常生效——否则「哪些控制项用不上」会被知识词表放过去。
    knowledge_question = bool(_LEVEL_KNOWLEDGE.search(text))
    # 指向提问者自己系统 / 第二人称：知识白名单在这些句子里不再豁免
    personal = bool(_SECOND_PERSON.search(text) or _OWN_SYSTEM.search(text))
    for index, pattern in enumerate(_UNDETERMINABLE_PATTERNS):
        if knowledge_question and index == 6:
            continue
        m = pattern.search(text)
        if m:
            return True, f"{_UNDETERMINABLE_LABEL}（命中「{m.group(0).strip()}」）"

    # 结构化兜底：分级词 × 判定动作（顺序、夹字都不影响）
    m_root = _APPLICABILITY_ROOT.search(text)
    if m_root:
        return True, f"{_UNDETERMINABLE_LABEL}（命中「{m_root.group(0)}」）"

    # 动作词闭集（第六轮）：等级怎么写是开放集合，但"向我们要一个合规判定"的
    # 动作是闭集。合规动作 + 指向自己/求结论 + 求结论尾巴 ⇒ 拦。
    # 例：「我们系统满足三级要求吗」「我们公司规模小，能不能免于等保」
    #     「按 3 星标准建设可以吗」「按 level three 建设可以吗」——不管等级
    #     写成什么，只要是在问"我们这样行不行"，都落在这里。
    m_action = _GRADE_ACTION.search(text)
    m_judge_any = _JUDGE_FEATURE.search(text)
    if m_action:
        m_tail = _DECISION_TAIL.search(text)
        if (
            m_tail
            and (personal or m_judge_any)
            and not (knowledge_question and not m_judge_any)
        ):
            return True, (
                f"{_UNDETERMINABLE_LABEL}"
                f"（命中合规动作「{m_action.group(0)}」+ 求结论「{m_tail.group(0)}」）"
            )

    m_level = _LEVEL_FEATURE.search(text)
    if m_level:
        m_judge = m_judge_any
        # 知识型问法（"等保三级建设流程有哪些步骤"）里出现"建设"不算要结论；
        # 一旦句中指向提问者自己的系统，知识白名单不再豁免。
        # 第五轮：删掉「"定" in m_level」的单字兜底——「定级」这个词本身不是
        # 判定动作，必须有第二人称 / 自有系统 / 要结论的信号才拦，
        # 否则「定级流程是什么」这类知识题会被误杀。
        if m_judge and not (knowledge_question and not personal):
            hit_judge = m_judge.group(0).strip()
            return True, (
                f"{_UNDETERMINABLE_LABEL}"
                f"（命中分级词「{m_level.group(0).strip()}」+ 判定动作「{hit_judge}」）"
            )
        if (
            "定" in m_level.group(0)
            and (_SECOND_PERSON.search(text) or _OWN_SYSTEM.search(text))
            and not _ALREADY_LEVELED.search(text)
            # 知识型流程题（"我们单位想了解一下定级备案的流程"）里的"定级"
            # 不是动作，是在问流程；没有求结论的尾巴就放行。
            and not (knowledge_question and not m_judge)
        ):
            return True, (
                f"{_UNDETERMINABLE_LABEL}"
                f"（命中分级词「{m_level.group(0).strip()}」，且指向提问者自己的系统）"
            )
    # 只有分级词、没有判定动作，但问的是"我们自己的系统"——定级同样不可答。
    # 属性豁免（"三级系统/三级要求"这类把等级当定语的说法）**只对真知识问法**成立：
    # 问「我们公司是三级系统，现在缺哪些日志」可以答；问「我们系统满足三级要求吗」
    # 是在要结论，必须拦——先按"分级词 + 自有系统"拦，再谈属性。
    if (
        m_level
        and _OWN_SYSTEM.search(text)
        and not _ALREADY_LEVELED.search(text)
        # 真知识问法（"我们单位定级备案的流程是什么"）问的是流程，不是要我们定级；
        # 只有带求结论尾巴（m_judge_any）时才落到下面的拦截。
        and not (knowledge_question and not m_judge_any)
    ):
        attribute_ok = bool(_LEVEL_AS_ATTRIBUTE.search(text)) and knowledge_question and not m_judge_any
        if not attribute_ok:
            return True, (
                f"{_UNDETERMINABLE_LABEL}"
                f"（命中分级词「{m_level.group(0).strip()}」，且问的是自己的系统）"
            )
    # 等保主题下的"建设 / 测评 / 整改 / 定级"意图：只要在说自己的系统，
    # 或带着求判定的尾巴，问的就是"我们该做到哪一级"，这同样是替用户下结论。
    m_es = _ES_LEVEL_INTENT.search(text)
    if m_es and not _ALREADY_LEVELED.search(text):
        if (_OWN_SYSTEM.search(text) or _JUDGE_FEATURE.search(text)) and not (
            # 知识型流程题（"我们公司做等保测评的步骤有哪些"）问的是步骤，
            # 没有求结论的尾巴就放行；带尾巴（要不要/够不够）照拦。
            knowledge_question and not m_judge_any
        ):
            return True, (
                f"{_UNDETERMINABLE_LABEL}"
                f"（命中等保建设/测评意图「{m_es.group(0).strip()}」，且要的是结论）"
            )
    # 闭集兜底（第四轮）：等级锚点 + 等保/定级语境，且不是知识型问法，
    # 一律当作"要我们替它判定等级"。这里刻意默认拒绝——多问一句只是麻烦，
    # 替用户下结论是致命的（两者的代价不对称）。
    anchor = _level_anchor_hit(text)
    tier = _TIER_WORD.search(text)
    # 档位表达单独出现太弱（"三层架构""第一阶段"），必须配上"自有系统/第二人称
    # + 判定动作"才算要我们替它定档。
    tier_structured = bool(
        tier
        and (_OWN_SYSTEM.search(text) or _SECOND_PERSON.search(text))
        and (_JUDGE_FEATURE.search(text) or _LEVEL_ACTION.search(text))
    )
    anchor_strong = bool(
        anchor
        and (
            _LEVEL_CONTEXT.search(text)
            or _LEVEL_DIRECTIVE.search(text)
            or _LEVEL_ACTION.search(text)
        )
    )
    if (anchor_strong or tier_structured) and not _LEVEL_KNOWLEDGE.search(text):
        hit_word = anchor or (tier.group(0).strip() if tier else "")
        return True, (
            f"{_UNDETERMINABLE_LABEL}"
            f"（命中等级/档位表达「{hit_word}」+ 定级/建设动作或语境，且不是知识型问法）"
        )
    return False, ""


def needs_system_context(
    question: str, history_text: str = ""
) -> tuple[bool, str]:
    """判断问题是否属于"无法在不了解具体系统的前提下回答"。

    第五轮：多轮追问也要拦。用户第二轮只说「就按这个来建设吧」，本轮没有
    任何等级词，但上一轮问的是"定到哪一级"——只看本轮就会漏判。所以本轮
    判定没命中、且含「按这个/照上面」这类指代时，用上一轮文本再判一次。
    """
    hit, reason = _grade_intent(question)
    if hit:
        return hit, reason
    text = normalize_for_match(question or "")
    if history_text and _REFERRAL.search(text):
        prev_hit, prev_reason = _grade_intent(history_text)
        if prev_hit:
            return True, f"{prev_reason}（本轮用「按这个/照上面」指代上一轮的等级问题，按上下文判定）"
    return False, ""


