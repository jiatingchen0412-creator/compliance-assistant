def clarify_notice() -> str:
    """问题太笼统时，拼在回答最前面的提示。

    为什么非要单独拼一段：模型漏问的时候，它给的那段结论读起来是
    "已经看过你的情况了"的口吻（"您的系统可能存在……"）。用户是不懂技术的，
    很容易把那当成针对自己的判断。所以要让用户第一眼就看到"我还没法判断"，
    而不是把希望寄托在模型自觉上。
    """
    return (
        "⚠️ 您说的情况还比较笼统，我先没法给出针对性的结论——"
        "同一个说法在不同系统上对应的条款可能完全不同。\n"
        "下面只是相关知识库条款的大致说明，具体怎么落到您这边，"
        "需要您先补充下面几个情况。\n"
    )


def out_of_kb_notice(names: list[str]) -> str:
    """用户点名了知识库外的法规时，拼在回答最前面的说明。

    这段话由服务端生成、强制拼接，模型删不掉。
    措辞要点：**先说不能做什么**（不转述该法规条文），
    再说还能做什么（给出库里真实收录的相关条款），最后给行动建议。
    """
    if not names:
        return ""
    listed = "、".join(names)
    covered = "、".join(COVERED_STANDARDS)
    return (
        f"⚠️ 先说明一点：您提到的 {listed} 不在本工具的知识库范围内。\n\n"
        f"本工具目前只收录了三套标准：{covered}。\n"
        f"所以下面的回答里不会出现 {listed} 的条文内容——"
        f"这类内容我不能凭记忆转述，转了也无法保证准确，那正是最容易误导您的地方。\n"
        f"如果需要该法规的准确条文，请查阅官方发布文本，或咨询专业安全顾问。\n\n"
        f"下面是知识库里确实收录的、与您问题主题相关的条款，供您对照参考。\n"
    )


