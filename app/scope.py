"""问题范围判定：识别两类"本工具答不了"的问题。

为什么需要这个模块
------------------
原来的防幻觉只做了一件事：**检索分数低于阈值就拒答**。这挡得住
"今天天气怎么样"，但挡不住两类更危险的问题：

一、用户点名了知识库外的法规
    问"《个人信息保护法》第13条怎么规定的"时，检索会命中等保里
    "个人信息保护"的条款（分数远高于阈值），于是系统认为"找到了"，
    直接把问题交给模型。模型会凭参数记忆转述那部法规的条文，
    再挂上等保的引用伪装成有据可查——**这是编造，而且用户看不出来**。
    实测编出来的内容本身就是错的（把第5、6条的原则安到了第13条上）。

二、问题本身无法判定
    问"列出等保三级里所有不适用的条款"时，"哪些适用"要结合系统定级、
    业务范围、部署模式逐条比对才能得出。模型不知道用户的系统长什么样，
    只能把检索到的条款号当成"不适用条款"吐出来——**答得越快越像真的，
    错得越离谱**。

两类问题的共同点：**检索分数都很高，阈值这道闸门拦不住**。
所以必须在"检索之后、调模型之前"再加一层判定。

设计原则：能由服务端拍板的，绝不交给模型
----------------------------------------
这两类问题的正确答案都是**确定性的**（"知识库没有这部法规"、
"这事无法判定"），不需要模型发挥。所以：
  - 判定由代码做（本模块），不依赖模型自觉；
  - 告知用户的那段话由服务端生成并**强制拼进回答**，
    模型删不掉、也改不了。

这样做的额外好处：**这两个保证可以离线验证**——不启动 Ollama
也能跑测试证明它是对的（见 tests/test_scope.py）。
"""
